import {test,expect} from '@playwright/test';

test('review ownership, verified change and check-ins preserve an honest result',async({page})=>{
 await page.addInitScript(()=>sessionStorage.setItem('rr_demo','true'));
 await page.goto('/');
 await page.getByRole('button',{name:'Product Reviews',exact:true}).click();
 await page.getByRole('button',{name:'Plan a product review',exact:true}).first().click();
 const form=page.getByRole('dialog');
 await expect(form.getByRole('combobox',{name:'Review owner'})).not.toHaveValue('');
 await form.getByLabel('Issue to reduce',{exact:true}).fill('Packaging damage check-in');
 await form.getByRole('textbox',{name:'Review goal'}).fill('Reduce return requests by protecting the product during transit.');
 await form.getByRole('textbox',{name:'Planned change'}).fill('Verify packaging strength and add protective corner inserts.');
 await form.getByRole('combobox',{name:'Review duration'}).selectOption('7');
 await form.getByRole('combobox',{name:'Return observation period'}).selectOption('14');
 await expect(form).toContainText('at least 21 days after the change');
 await form.getByRole('button',{name:'Save review plan'}).click();
 await expect(form).not.toBeVisible();
 const cycle=page.locator('.review-cycle').filter({hasText:'Reduce return requests by protecting the product during transit.'});
 await expect(cycle).toContainText('Owner:');
 await cycle.getByRole('button',{name:'Record change applied'}).click();
 const decision=page.getByRole('dialog');
 await expect(decision.getByRole('button',{name:'Start feedback review'})).toBeDisabled();
 await decision.getByRole('textbox',{name:'Applied change note'}).fill('Checked a packed sample and added the protective inserts to the dispatch process.');
 await decision.getByRole('checkbox').check();
 await decision.getByRole('button',{name:'Start feedback review'}).click();
 await expect(decision).not.toBeVisible();
 await expect(cycle).toContainText('Earliest full comparison:');
 await expect(cycle).toContainText('Observed so far');
 await expect(cycle).toContainText('Checked a packed sample');
 await cycle.getByRole('button',{name:'Review results'}).click();
 await expect(decision.getByRole('radio',{name:'Continue monitoring'})).toBeChecked();
 await decision.getByRole('textbox',{name:'Review outcome'}).fill('Fresh sales and return requests are still limited. Keep the change consistent and check again.');
 await decision.getByRole('combobox',{name:'Next check-in'}).selectOption('14');
 await decision.getByRole('button',{name:'Save check-in'}).click();
 await expect(decision).not.toBeVisible();
 await cycle.locator('.review-checkpoints summary').click();
 await expect(cycle.locator('.review-checkpoints')).toContainText('Keep the change consistent and check again.');
 await cycle.getByRole('button',{name:'Review results'}).click();
 await decision.getByRole('radio',{name:'Keep the change',exact:false}).check();
 await decision.getByRole('textbox',{name:'Review outcome'}).fill('The packing checks passed. Keep the inserts, with no claim of a measured return reduction yet.');
 await decision.getByRole('button',{name:'Save completed review'}).click();
 await expect(decision).not.toBeVisible();
 await page.getByRole('combobox',{name:'Review status'}).selectOption('completed');
 await expect(cycle).toContainText('Keep the change');
 await expect(cycle).toContainText('closed before a full comparison was available');
});

